import { DocketEntry } from '../DocketEntry';
import { NOTICE_OF_CHANGE_CONTACT_INFORMATION_EVENT_CODES } from '../EntityConstants';

const formatPartyNames = (names: string[], prefix: string): string => {
  if (names.length === 0) return '';
  const joinedNames = names.join(' & ');
  return names.length === 1
    ? `${prefix}. ${joinedNames}`
    : `${prefix}s. ${joinedNames}`;
};

export const generateFiledBy = ({
  docketEntry,
  petitioners,
}: {
  docketEntry: RawDocketEntry;
  petitioners: any[];
}): string | undefined => {
  const isNoticeOfContactChange =
    NOTICE_OF_CHANGE_CONTACT_INFORMATION_EVENT_CODES.includes(
      docketEntry.eventCode,
    );

  const shouldGenerateFiledBy =
    !(isNoticeOfContactChange && docketEntry.isAutoGenerated) &&
    !DocketEntry.isServed(docketEntry);

  if (!shouldGenerateFiledBy) return docketEntry.filedBy;

  const partiesArray: string[] = [];

  const privatePractitionerIsFiling = docketEntry.privatePractitioners?.some(
    practitioner => practitioner.partyPrivatePractitioner,
  );

  if (privatePractitionerIsFiling) {
    docketEntry.privatePractitioners?.forEach(practitioner => {
      if (practitioner.partyPrivatePractitioner) {
        partiesArray.push(practitioner.name);
      }
    });
    return docketEntry.otherFilingParty
      ? `${partiesArray.join(' & ')}, ${docketEntry.otherFilingParty}`
      : partiesArray.join(' & ');
  }

  if (docketEntry.partyIrsPractitioner) {
    partiesArray.push('Resp.');
  }

  const petitionersArray: string[] = [];
  const intervenorsArray: string[] = [];

  docketEntry.filers?.forEach(contactId =>
    petitioners.forEach(p => {
      if (p.contactId === contactId) {
        if (p.contactType == 'intervenor') {
          intervenorsArray.push(p.name);
        } else {
          petitionersArray.push(p.name);
        }
      }
    }),
  );

  const formattedPetitioners = formatPartyNames(petitionersArray, 'Petr');
  const formattedIntervenors = formatPartyNames(intervenorsArray, 'Intv');

  if (formattedPetitioners) partiesArray.push(formattedPetitioners);
  if (formattedIntervenors) partiesArray.push(formattedIntervenors);

  const filedByArray = partiesArray.length ? [partiesArray.join(' & ')] : [];
  if (docketEntry.otherFilingParty) {
    filedByArray.push(docketEntry.otherFilingParty);
  }

  return filedByArray.join(', ') || docketEntry.filedBy;
};
