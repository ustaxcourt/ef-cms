import { Get } from 'cerebral';
import { state } from '@web-client/presenter/app.cerebral';
import { getFilerParties } from '@web-client/presenter/computeds/getFilerParties';

export const fileAutoGeneratedDocumentReviewHelper = (get: Get): any => {
  const form = get(state.form);
  const caseDetail = get(state.caseDetail);

  const formattedParties = getFilerParties({
    caseDetail,
    filersMap: form.filersMap,
  });

  return {
    formattedParties,
  };
};
