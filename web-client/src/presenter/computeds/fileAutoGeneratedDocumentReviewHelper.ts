import { Get } from 'cerebral';
import { state } from '@web-client/presenter/app.cerebral';
import { ROLES } from '@shared/business/entities/EntityConstants';
import { getFilerParties } from '@web-client/presenter/computeds/getFilerParties';

export const fileAutoGeneratedDocumentReviewHelper = (get: Get): any => {
  const form = get(state.form);
  const user = get(state.user);
  const caseDetail = get(state.caseDetail);

  const formattedParties = getFilerParties({
    caseDetail,
    filersMap:
      form.eventCode === 'NOTW'
        ? form.partiesToWithdrawFromMap
        : form.filersMap,
  });

  let partiesHeaderText = 'Parties Filing The Document(s)';
  let partiesLabelText = 'Filing Parties';
  if (
    form.eventCode === 'NOTW' &&
    (user.role === ROLES.privatePractitioner ||
      user.role === ROLES.irsPractitioner)
  ) {
    partiesHeaderText = "Parties You're Withdrawing From as Counsel";
    partiesLabelText = 'Parties';
  }

  return {
    formattedParties,
    partiesHeaderText,
    partiesLabelText,
  };
};
