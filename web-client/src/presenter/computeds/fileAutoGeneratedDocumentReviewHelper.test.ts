import { runCompute } from '@web-client/presenter/test.cerebral';
import { fileAutoGeneratedDocumentReviewHelper } from './fileAutoGeneratedDocumentReviewHelper';
import { ROLES } from '@shared/business/entities/EntityConstants';

describe('fileAutoGeneratedDocumentReviewHelper', () => {
  it('should return the default text values', () => {
    const result = runCompute(fileAutoGeneratedDocumentReviewHelper, {
      state: {
        form: {
          eventCode: 'not an event code',
        },
        user: {
          role: ROLES.petitioner,
        },
      },
    });

    expect(result.partiesHeaderText).toEqual('Parties Filing The Document(s)');
    expect(result.partiesLabelText).toEqual('Filing Parties');
  });
  it('should return proper text values for a NOTW event code', () => {
    const result = runCompute(fileAutoGeneratedDocumentReviewHelper, {
      state: {
        form: {
          eventCode: 'NOTW',
        },
        user: {
          role: ROLES.irsPractitioner,
        },
      },
    });

    expect(result.partiesHeaderText).toEqual(
      "Parties You're Withdrawing From as Counsel",
    );
    expect(result.partiesLabelText).toEqual('Parties');
  });
});
